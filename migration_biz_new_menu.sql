-- ============================================================
-- محیطِ فروشگاهی — چیدمانِ منوی «+ ثبتِ جدید»
-- ============================================================
--
-- **خواسته‌ی مالکِ نصب:** «+ می‌زنم… دوست دارم مثلِ عکسِ دوم بشه (کاشی با
-- آیکون) و امکانِ اضافه کردن و پاک کردن داشته باشم؛ مشتری یا تأمین‌کننده و
-- محصول نباشن بهتره.»
--
-- ⛔ `new_menu` = فهرستِ JSONِ کلیدهای `Biz::NEW_MENU` که این فروشگاه می‌خواهد،
--    به ترتیبِ همان کاتالوگ. `NULL` = پیش‌فرض (`Biz::NEW_DEFAULT`)، پس پیش‌فرضِ
--    فردا به همه می‌رسد. کلیدِ ناشناخته هنگامِ خواندن دور ریخته می‌شود. روی
--    `biz_settings` است نه `localStorage`: همان دلیلِ رنگِ فروشگاه — روی هر
--    دستگاه یکی، و سرور بی‌اسکریپت رندرش می‌کند. ایدمپوتنت.

ALTER TABLE `biz_settings`
    ADD COLUMN IF NOT EXISTS `new_menu` VARCHAR(1000) NULL DEFAULT NULL
        COMMENT 'کلیدهای منوی «+» — Biz::newMenu()';
