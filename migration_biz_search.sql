-- ============================================================
-- محیطِ فروشگاهی — جست‌وجوی کالا و «شرحِ کالا» روی ردیفِ فاکتور
-- ============================================================
--
-- **گزارشِ مالکِ نصب:** «سرچِ کالا اصلاً کار نمی‌کنه، یعنی کالا معرفی شده
-- اما نمیاره که فاکتور بزنم.»
--
-- ۱. ⛔ `utf8mb4_persian_ci` حرفِ عربیِ «ي/ك» را با فارسیِ «ی/ک» **یکی
--    نمی‌داند** (سنجیده شد: `'ي' = 'ی'` → 0). کالایی که از اکسل یا
--    ووکامرس آمده اغلب «ي» عربی دارد و کاربر با کیبوردِ فارسی «ی» تایپ
--    می‌کند؛ پس نه فهرستِ پیشنهادِ مرورگر پیدایش می‌کرد، نه تطبیقِ سرور،
--    نه جست‌وجوی فهرستِ کالا — بی‌هیچ خطایی. نام‌ها یک بار یکسان می‌شوند
--    (از این به بعد `BizProducts::save()` خودش یکسان می‌نویسد).
--    ⚠ `REPLACE` با رشته‌ی ثابت است، پس «Illegal mix of collations» ممکن
--    نیست (رشته‌ی ثابت به collationِ ستون تبدیل می‌شود).
--
-- **خواسته‌ی مالکِ نصب:** «نام کالا باید جاش کوچیکتر بشه و کنارش شرح کالا
-- بیاد که درمورد گوشی باید imei بخوره یا توضیحات برای کالاها بغیر گوشی.»
--
-- ⛔ فقط افزودنی و فقط `biz_*`. هیچ جدولِ حساب لندِ شخصی دست نمی‌خورد.
--
-- ۲. `biz_invoice_lines.note` — توضیحِ آزادِ ردیف (رنگ، گارانتی، سریال…).
-- ⛔ جدا از `description` است، نه جایش: `description` نامِ کالا در لحظه‌ی
-- صدور است و گزارش و کاردکس و برگشت از آن می‌خوانند؛ نوشتنِ توضیح داخلِ
-- آن یعنی «گلس سامسونگ — مشکی» و «گلس سامسونگ — سفید» دو کالای متفاوت
-- در گزارش. برای گوشی جای شرح را IMEI می‌گیرد (`imei1`/`imei2`).
--
-- شاهدِ `migrate.sh`: `biz_invoice_lines.note`. ایدمپوتنت.

ALTER TABLE `biz_invoice_lines`
    ADD COLUMN IF NOT EXISTS `note` VARCHAR(190) NULL DEFAULT NULL AFTER `imei2`;

UPDATE `biz_products`
   SET `name` = REPLACE(REPLACE(REPLACE(`name`, 'ي', 'ی'), 'ك', 'ک'), 'ى', 'ی')
 WHERE `name` LIKE '%ي%' OR `name` LIKE '%ك%' OR `name` LIKE '%ى%';
