-- «کدام قلم‌ها روی صفحه‌ی خانه دیده شوند؟» — تنظیماتِ هر کاربر.
--
-- ⛔ فهرستِ **خاموش‌ها** ذخیره می‌شود، نه روشن‌ها. `NULL` (و رشته‌ی
--    خالی) یعنی «همه روشن» — پیش‌فرضِ همه. دو دلیل:
--    ۱. هیچ نصبِ موجودی بعد از `git pull` خانه‌اش عوض نمی‌شود.
--    ۲. قلمی که فردا به `HOME_WIDGETS` اضافه شود برای همه **روشن** می‌آید؛
--       با ذخیره‌ی روشن‌ها، هر کسی که یک بار چیزی را خاموش کرده بود قلمِ
--       تازه را هرگز نمی‌دید — بی‌آنکه بداند وجود دارد.
--
-- ⛔ چرا ستونِ دیتابیس و نه `localStorage` (مثلِ `daftar_palette`):
--    رنگ یک **نگاه** است و باید پیش از رندر اعمال شود؛ این یکی تصمیمِ
--    ماندگار درباره‌ی **محتوای** خانه است — همان استدلالِ `wallets.pinned`.
--    و سرور با دانستنش قلمِ خاموش را **حساب نمی‌کند** (کوئریِ
--    `topGrowingCategory()` زده نمی‌شود) و جمله‌ی بعدی جای آن را می‌گیرد.
--
-- ⚠ کلیدهای مجاز فقط در `HOME_WIDGETS` (includes/functions.php) است و
--   هنگامِ خواندن و نوشتن با همان صافی می‌شود؛ کلیدِ ناشناخته نادیده
--   گرفته می‌شود.
ALTER TABLE `users`
    ADD COLUMN IF NOT EXISTS `home_hidden` VARCHAR(255) NULL DEFAULT NULL
        COMMENT 'قلم‌های خاموشِ خانه، با ویرگول. NULL = همه روشن';
