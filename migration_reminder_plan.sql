-- یادآورِ چنددوره‌ای: «۱۲ قسط» به‌جای دوازده بار ثبتِ دستی.
--
-- ⛔ چرا شمارنده روی خودِ قانون و نه دوازده ردیفِ جدا:
--    همان دلیلی که `debtInstallments()` هیچ ردیفِ قسطی ذخیره نمی‌کند —
--    ۱۲ ردیف به‌ازای هر تعهد جدول را سریع بزرگ می‌کند، و عوض کردنِ
--    تعدادِ اقساط یعنی بازسازیِ همه‌ی ردیف‌های انجام‌نشده. یک قانون با
--    «چندمین از چندتا» همان اطلاعات را می‌دهد و ویرایشش یک UPDATE است.
--
-- ⚠ `total_count = 0` یعنی **بی‌پایان** (تا وقتی کاربر حذفش کند)، نه
--   «صفر بار». پیش‌فرض همین است تا یادآورهای موجود دست‌نخورده بمانند:
--   آن‌ها تکرارِ بی‌پایان داشتند و باید همان بمانند.
--
-- ⛔ `total_amount` جدا از `amount` است و هر دو لازم‌اند: `amount` مبلغِ
--    **همین قسط** است (چیزی که در اعلان و کارت دیده می‌شود) و
--    `total_amount` جمعِ کلِ تعهد. با یکی از این دو، یا باقیمانده‌ی
--    تقسیم گم می‌شد (جمعِ اقساط با کل نمی‌خواند) یا کارت نمی‌توانست
--    بگوید «۱۲ میلیون در ۱۲ قسط».
ALTER TABLE `reminders`
    ADD COLUMN IF NOT EXISTS `total_count`  SMALLINT UNSIGNED NOT NULL DEFAULT 0 AFTER `notify_days_before`,
    ADD COLUMN IF NOT EXISTS `done_count`   SMALLINT UNSIGNED NOT NULL DEFAULT 0 AFTER `total_count`,
    ADD COLUMN IF NOT EXISTS `total_amount` BIGINT NULL AFTER `done_count`;

-- ⛔ `recurrence_type` از قبل VARCHAR(20) است و مقدارِ تازه‌ی
--    `every_n_days` هیچ تغییرِ ساختاری نمی‌خواهد — عمداً ENUM نشد،
--    چون هر مقدارِ تازه یک ALTER روی جدولِ زنده می‌خواست.
