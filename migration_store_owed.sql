-- ---------------------------------------------------------------
-- migration_store_owed.sql — سطلِ «طلبِ سهامدارانِ فروشگاه»
--
-- ⛔ چرا ستونِ تازه و نه ریختن در `store_total`
--
-- مالکِ نصب خواست بتواند سه چیز را از هم جدا ببیند:
--
--     داراییِ خودِ فروشگاه  →  store_total  (خالص، `totalEquity`)
--     داراییِ بچه‌ها        →  store_owed   (جمعِ طلبِ سهامدارها)
--     باهم                 →  جمعِ این دو
--
-- صفحه‌ی دارایی برای هر قلم یک کلیدِ روشن/خاموش دارد، پس «باهم» و
-- «جدا» همان مکانیزمِ موجود است و چیزِ تازه‌ای در رابط لازم نبود. ولی
-- عکسِ روزانه اجزا را **جدا** ذخیره می‌کند و قاعده‌ی نوشته‌شده این
-- است که نامِ سطل دقیقاً همان `kind` باشد. ریختنِ هر دو در یک ستون،
-- جمعِ کل را درست نگه می‌داشت و اجزا را **بی‌صدا** غلط می‌کرد — دقیقاً
-- همان خرابی‌ای که `migration_store_share` هم برایش دو ستونِ جدا ساخت.
--
-- ⚠ ایدمپوتنت است و روی نصبی که ستون را دارد هیچ کاری نمی‌کند.
-- ---------------------------------------------------------------

ALTER TABLE `net_worth_snapshots`
    ADD COLUMN IF NOT EXISTS `store_owed` BIGINT NOT NULL DEFAULT 0
    COMMENT 'جمعِ طلبِ سهامدارانِ فروشگاه — فقط برای مدیر';

SELECT 'migration_store_owed با موفقیت اجرا شد.' AS result;
