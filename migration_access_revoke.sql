-- «از این لحظه به بعد، هر نشستِ قدیمی‌ترِ این کاربر بی‌اعتبار است.»
--
-- ⛔ چرا لازم است: نشستِ PHP فقط یک فایل روی دیسک است و به هیچ چیزی در
--    دیتابیس بند نیست. «غیرفعال کردنِ کاربر»، «عوض کردنِ رمز» و «خروج
--    از همه‌ی دستگاه‌ها» تا امروز فقط `trusted_devices` و `api_tokens`
--    را پاک می‌کردند — یعنی مرورگری که همان لحظه وارد بود، تا وقتی
--    خودش خارج نمی‌شد (و با «بدون مهلت» یعنی هرگز) وارد می‌ماند.
--
-- `Auth::isLoggedIn()` این ستون را با `login_time`ِ نشست می‌سنجد (حداکثر
-- یک بار در دقیقه، نه هر درخواست): نشستی که پیش از این لحظه ساخته شده
-- خالی می‌شود. تنها جای نوشتنش `revokeAllAccessFor()` است.
--
-- ⚠ NULL = هرگز باطل نشده. پس نصب‌های موجود بعد از `git pull` هیچ
--   کاربری را بیرون نمی‌اندازند.
--
-- ⚠ مقایسه کاملاً در دیتابیس انجام می‌شود (`FROM_UNIXTIME(:login)` در
--   برابر این ستون) — همان درسِ لینکِ بازیابیِ رمز: منطقه‌ی زمانیِ PHP
--   و MySQL یکی نیست و مقایسه‌ی دو طرفه بی‌صدا غلط می‌شود.
ALTER TABLE `users`
    ADD COLUMN IF NOT EXISTS `access_revoked_at` DATETIME NULL DEFAULT NULL
        COMMENT 'نشست‌های قدیمی‌تر از این لحظه بی‌اعتبارند؛ NULL = هرگز'
        AFTER `is_active`;
