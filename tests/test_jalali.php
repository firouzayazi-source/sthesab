<?php
/**
 * تست توابع تاریخ شمسی — خطرناک‌ترین نقطه‌ی اپ.
 *
 * چرا خطرناک: تاریخ در دیتابیس میلادی ذخیره می‌شود ولی همه‌جا شمسی نمایش
 * داده و شمسی وارد می‌شود. اگر تبدیل یک روز خطا کند، تراکنش با تاریخ
 * اشتباه ثبت می‌شود و هیچ خطایی هم بالا نمی‌آید — فقط گزارش‌ها بی‌سروصدا
 * غلط می‌شوند. بدتر: دو پیاده‌سازی مستقل وجود دارد (PHP و JS تقویم) که
 * باید همیشه یکی بمانند.
 */

require_once __DIR__ . '/lib/assert.php';
require_once __DIR__ . '/../includes/functions.php';

// ---------------------------------------------------------------
T::group('نقاط مرجع — تاریخ‌هایی که مقدارشان مستقل قابل تأیید است');

// مبنا: ۱ فروردین هر سال با اعتدال بهاری شروع می‌شود.
$anchors = [
    // [jy, jm, jd, gy, gm, gd]
    [1400,  1,  1, 2021,  3, 21],
    [1401,  1,  1, 2022,  3, 21],
    [1402,  1,  1, 2023,  3, 21],
    [1403,  1,  1, 2024,  3, 20],   // ۱۴۰۳ کبیسه است
    [1404,  1,  1, 2025,  3, 21],
    [1405,  1,  1, 2026,  3, 21],
    [1403, 12, 30, 2025,  3, 20],   // آخرین روز سال کبیسه
    [1404, 12, 29, 2026,  3, 20],   // آخرین روز سال عادی
    [1399, 12, 30, 2021,  3, 20],   // ۱۳۹۹ کبیسه بود
];
foreach ($anchors as [$jy, $jm, $jd, $gy, $gm, $gd]) {
    T::same([$gy, $gm, $gd], jalaliToGregorian($jy, $jm, $jd),
        sprintf('%04d/%02d/%02d شمسی → میلادی', $jy, $jm, $jd));
    T::same([$jy, $jm, $jd], gregorianToJalali($gy, $gm, $gd),
        sprintf('%04d-%02d-%02d میلادی → شمسی', $gy, $gm, $gd));
}

// ---------------------------------------------------------------
T::group('رفت و برگشت — هر روز باید به خودش برگردد');

$bad = [];
$checked = 0;
for ($jy = 1300; $jy <= 1500; $jy++) {
    $lenEsfand = jalaliMonthLength($jy, 12);
    for ($jm = 1; $jm <= 12; $jm++) {
        $len = ($jm <= 6) ? 31 : (($jm <= 11) ? 30 : $lenEsfand);
        for ($jd = 1; $jd <= $len; $jd++) {
            $checked++;
            [$gy, $gm, $gd] = jalaliToGregorian($jy, $jm, $jd);
            [$ry, $rm, $rd] = gregorianToJalali($gy, $gm, $gd);
            if ([$ry, $rm, $rd] !== [$jy, $jm, $jd]) {
                $bad[] = sprintf('%04d/%02d/%02d → %04d-%02d-%02d → %04d/%02d/%02d',
                    $jy, $jm, $jd, $gy, $gm, $gd, $ry, $rm, $rd);
            }
        }
    }
}
T::bulk($checked, $bad, 'رفت و برگشت شمسی←→میلادی، سال‌های ۱۳۰۰ تا ۱۵۰۰');

// ---------------------------------------------------------------
T::group('پیوستگی — هر روز باید دقیقاً یک روز بعد از روز قبل باشد');

// این تست چیزی را می‌گیرد که رفت‌وبرگشت نمی‌گیرد: اگر تبدیل روزی را جا
// بیندازد یا دوبار بشمارد، رفت‌وبرگشت هنوز درست کار می‌کند ولی فاصله‌ی
// روزها غلط می‌شود — و محاسبه‌ی «هفته‌ی گذشته» یا «۳۰ روز اخیر» خراب.
$bad = [];
$checked = 0;
$prev = null;
for ($jy = 1395; $jy <= 1415; $jy++) {
    for ($jm = 1; $jm <= 12; $jm++) {
        $len = ($jm <= 6) ? 31 : (($jm <= 11) ? 30 : jalaliMonthLength($jy, 12));
        for ($jd = 1; $jd <= $len; $jd++) {
            [$gy, $gm, $gd] = jalaliToGregorian($jy, $jm, $jd);
            $ts = gmmktime(0, 0, 0, $gm, $gd, $gy);
            $checked++;
            if ($prev !== null && ($ts - $prev) !== 86400) {
                $bad[] = sprintf('%04d/%02d/%02d — فاصله با روز قبل: %d ثانیه',
                    $jy, $jm, $jd, $ts - $prev);
            }
            $prev = $ts;
        }
    }
}
T::bulk($checked, $bad, 'فاصله‌ی هر روز با روز قبلش دقیقاً ۲۴ ساعت است');

// ---------------------------------------------------------------
T::group('طول ماه و سال کبیسه');

foreach ([1, 2, 3, 4, 5, 6] as $m) {
    T::same(31, jalaliMonthLength(1404, $m), "ماه $m باید ۳۱ روز باشد");
}
foreach ([7, 8, 9, 10, 11] as $m) {
    T::same(30, jalaliMonthLength(1404, $m), "ماه $m باید ۳۰ روز باشد");
}

// سال‌های کبیسه‌ی شناخته‌شده: اسفند ۳۰ روز
foreach ([1399, 1403, 1408] as $jy) {
    T::same(30, jalaliMonthLength($jy, 12), "اسفند $jy (کبیسه) باید ۳۰ روز باشد");
}
foreach ([1400, 1401, 1402, 1404, 1405] as $jy) {
    T::same(29, jalaliMonthLength($jy, 12), "اسفند $jy (عادی) باید ۲۹ روز باشد");
}

// طول سال باید همیشه ۳۶۵ یا ۳۶۶ باشد — نه چیز دیگری
$bad = [];
for ($jy = 1300; $jy <= 1500; $jy++) {
    $a = gmmktime(0, 0, 0, ...array_slice(
        [null, ...jalaliToGregorian($jy, 1, 1)], 2, 2)) ;
    [$gy1, $gm1, $gd1] = jalaliToGregorian($jy, 1, 1);
    [$gy2, $gm2, $gd2] = jalaliToGregorian($jy + 1, 1, 1);
    $days = (int)round((gmmktime(0,0,0,$gm2,$gd2,$gy2) - gmmktime(0,0,0,$gm1,$gd1,$gy1)) / 86400);
    if ($days !== 365 && $days !== 366) {
        $bad[] = "سال $jy طولش $days روز شد";
    }
}
T::bulk(201, $bad, 'طول هر سال شمسی ۳۶۵ یا ۳۶۶ روز است');

// ---------------------------------------------------------------
T::group('توابع کمکی تاریخ');

// toJalali تابع نمایشی است و عمداً ارقام فارسی برمی‌گرداند
T::same('۱۴۰۴/۰۱/۰۱', toJalali('2025-03-21'), 'toJalali روی رشته‌ی میلادی');
T::same('۱۴۰۳/۱۲/۳۰', toJalali('2025-03-20'), 'toJalali روی آخرین روز سال کبیسه');
T::same('1404/01/01', toLatinDigits(toJalali('2025-03-21')), 'toLatinDigits ارقام را برمی‌گرداند');
T::ok(isValidDate('2025-03-21'), 'isValidDate تاریخ درست را می‌پذیرد');
T::ok(!isValidDate('2025-13-01'), 'isValidDate ماه ۱۳ را رد می‌کند');
T::ok(!isValidDate('2025-02-30'), 'isValidDate ۳۰ فوریه را رد می‌کند');
T::ok(!isValidDate('نامعتبر'), 'isValidDate رشته‌ی بی‌ربط را رد می‌کند');

exit(T::report());
