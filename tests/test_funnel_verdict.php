<?php
/**
 * تفسیرِ قیفِ شروع در `admin/insights.php`.
 *
 * ⛔ خطرِ اصلیِ این تابع هم — مثل جمله‌های بینشِ صفحه‌ی خانه — **دروغ
 *    گفتن** است، نه نبودن. ولی اینجا عارضه‌اش بزرگ‌تر است: مخاطبش مالکِ
 *    نصب است و حکمِ این کارت قرار است تعیین کند **کدام کار بعد انجام
 *    شود**. یک حکمِ غلط یعنی هفته‌ها کارِ اشتباه.
 *
 *    پس مهم‌ترین بررسی‌های اینجا هم «چه چیزی نباید گفته شود» است:
 *      • با نمونه‌ی کوچک هیچ تشخیصی داده نمی‌شود، حتی اگر عددها فاجعه باشند.
 *      • افتِ بالای قیف بر افتِ پایینِ آن مقدم است.
 *      • درصدِ هر پله نسبت به **پله‌ی قبلی** حساب می‌شود، نه نسبت به کل.
 *
 * این تابع خالص است و به دیتابیس دست نمی‌زند، پس بدون config هم اجرا
 * می‌شود.
 */

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit('Not found.');
}

require_once __DIR__ . '/lib/assert.php';
require_once __DIR__ . '/../includes/admin_insights.php';

/** قیفی با همان شکلی که `onboardingFunnel()` می‌سازد. */
$funnel = function (int $total, int $one, int $five, int $keep): array {
    $pc = fn($n) => $total > 0 ? (int)round($n * 100 / $total) : 0;
    return [
        ['label' => 'حساب ساخته',              'n' => $total, 'pc' => 100],
        ['label' => 'اولین تراکنش را ثبت کرده', 'n' => $one,   'pc' => $pc($one)],
        ['label' => 'دست‌کم ۵ تراکنش',          'n' => $five,  'pc' => $pc($five)],
        ['label' => 'در ۱۴ روز اخیر فعال',      'n' => $keep,  'pc' => $pc($keep)],
    ];
};

// ---------------------------------------------------------------
T::group('⛔ نمونه‌ی کوچک هیچ تشخیصی نمی‌گیرد');

// ⛔ این بدترین قیفِ ممکن است (هیچ‌کس حتی یک تراکنش ثبت نکرده) ولی فقط
//    چهار کاربر دارد. اگر نگهبانِ نمونه‌ی کوچک **بعد** از شاخه‌ی «bad»
//    بیاید، همین ورودی حکمِ قطعیِ «مشکل در دقیقه‌ی اول است» می‌گیرد —
//    یعنی مالکِ نصب از روی رفتارِ چهار نفر فرمِ ثبت را بازنویسی می‌کند.
//    ترتیبِ دروازه‌ها اینجا خودش منطق است، نه سلیقه.
$v = funnelVerdict($funnel(4, 0, 0, 0));
T::same('info', $v['tone'],
    '⛔ با ۴ کاربر حتی قیفِ صفر هم حکمِ قطعی نمی‌گیرد');
T::ok(!str_contains($v['advice'], '٪'),
    '⛔ و هیچ درصدی هم گفته نمی‌شود — درصدِ چهارتایی یعنی «یک نفر»');

$v = funnelVerdict($funnel(0, 0, 0, 0));
T::same('info', $v['tone'], 'دیتابیسِ خالی هم خطا نمی‌دهد');

// ---------------------------------------------------------------
T::group('⛔ افتِ بالای قیف مقدم است');

// هر سه پله خراب‌اند. حکم باید **اولی** را بگوید: تا کاربر اولین تراکنش
// را ثبت نکرده، حرف زدن از «۵ تراکنش» و «ماندگاری» بی‌معناست.
$v = funnelVerdict($funnel(40, 8, 1, 1));
T::same('bad', $v['tone'], 'قیفی که در پله‌ی اول می‌ریزد حکمِ bad می‌گیرد');
T::ok(str_contains($v['headline'], 'دقیقه'),
    '⛔ و حکم درباره‌ی همان پله‌ی اول است، نه ماندگاری');
T::ok(str_contains($v['advice'], 'ثبت'),
    'قدمِ بعدی هم گفته می‌شود، نه فقط تشخیص');

// پله‌ی اول سالم، پله‌ی دوم خراب
$v = funnelVerdict($funnel(40, 30, 6, 25));
T::same('warn', $v['tone'], 'افتِ پله‌ی دوم حکمِ warn می‌گیرد');
T::ok(str_contains($v['headline'], 'ادامه'), 'و حکمش درباره‌ی ادامه ندادن است');

// دو پله‌ی اول سالم، ماندگاری خراب
$v = funnelVerdict($funnel(40, 30, 20, 6));
T::same('warn', $v['tone'], 'افتِ ماندگاری هم warn است');
T::ok(str_contains($v['headline'], 'می‌رود'), 'و حکمش درباره‌ی برنگشتن است');

// ---------------------------------------------------------------
T::group('⛔ درصد نسبت به پله‌ی قبل، نه نسبت به کل');

// ⛔ ۱۰ نفر از ۲۰ نفر شروع کرده‌اند و ۵ نفر از **همان ۱۰ نفر** به ۵
//    تراکنش رسیده‌اند: یعنی ۵۰٪، که سالم است. اگر مخرج اشتباهاً «کل
//    کاربران» گرفته شود همان عدد ۲۵٪ خوانده می‌شود و قیفِ سالم «خراب»
//    اعلام می‌گردد — و مالکِ نصب دنبالِ مشکلی می‌گردد که وجود ندارد.
//    همین یک ورودی هر دو مخرجِ غلط (pcFive و pcKeep) را می‌گیرد.
$v = funnelVerdict($funnel(20, 10, 5, 5));
T::same('good', $v['tone'],
    '⛔ مخرجِ پله‌های بعدی «کسانی که شروع کرده‌اند» است، نه «همه‌ی کاربران»');

// و مرزها: دقیقاً ۵۰٪ فعال‌سازی هنوز «bad» نیست (شرط < ۵۰ است)
T::ok(str_contains($v['advice'], '۵۰'), 'و همان ۵۰٪ در متنِ حکم دیده می‌شود');

// قیفِ بی‌ابهامِ سالم، دور از هر مرزی
$v = funnelVerdict($funnel(50, 45, 35, 30));
T::same('good', $v['tone'], 'قیفِ آشکارا سالم، سالم خوانده می‌شود');
T::ok(str_contains($v['advice'], 'تازه') || str_contains($v['advice'], 'بیشتر'),
    'و قدمِ بعدی‌اش «حالا سراغِ رشد بروید» است');

// ---------------------------------------------------------------
T::group('⛔ هیچ حکمی نصفه یا مارک‌داون نیست');

// ⚠ متنِ حکم با `h()` در HTML چاپ می‌شود، نه مارک‌داون: ستاره‌ی تأکید
//   عیناً روی صفحه دیده می‌شود. یک بار همین شد.
$all = [
    'کوچک'      => $funnel(3, 0, 0, 0),
    'bad'       => $funnel(40, 8, 1, 1),
    'warn-۵تا'  => $funnel(40, 30, 6, 25),
    'warn-ماند' => $funnel(40, 30, 20, 6),
    'good'      => $funnel(50, 45, 35, 30),
];
foreach ($all as $name => $f) {
    $v = funnelVerdict($f);
    T::ok(($v['headline'] ?? '') !== '' && ($v['advice'] ?? '') !== '',
        "حکمِ «{$name}» هم عنوان دارد هم قدمِ بعدی");
    T::ok(!str_contains($v['headline'] . $v['advice'], '*'),
        "⚠ حکمِ «{$name}» ستاره‌ی مارک‌داون ندارد — با h() چاپ می‌شود");
    T::ok(in_array($v['tone'], ['info', 'bad', 'warn', 'good'], true),
        "لحنِ «{$name}» یکی از چهار کلاسِ CSS است");
}

exit(T::report());
