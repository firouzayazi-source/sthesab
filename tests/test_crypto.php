<?php
/**
 * تستِ رمزنگاریِ داده‌ی حساس (شماره کارت، شماره حساب، شبا).
 *
 * ⛔ چیزی که اگر بشکند، **داده از دست می‌رود** — نه اینکه ظاهر خراب
 *    شود. سه چیز که این تست نگه می‌دارد:
 *
 *  ۱. **رفت‌وبرگشتِ کامل.** هر رشته‌ای که رمز می‌شود باید دقیقاً همان
 *     برگردد — ارقام فارسی، فاصله، رشته‌ی بلند، همه.
 *
 *  ۲. **مقدارِ خامِ قدیمی باید همچنان خوانده شود.** ردیف‌هایی که پیش از
 *     روشن شدنِ رمزنگاری ذخیره شده‌اند دست‌نخورده‌اند؛ اگر
 *     `decrypt()` روی آن‌ها `null` بدهد، همه‌ی شماره‌کارت‌های موجود
 *     ناگهان ناپدید می‌شوند.
 *
 *  ۳. **دست‌کاری باید گرفته شود.** الگوریتم احراز اصالت دارد؛ اگر روزی
 *     به چیزی بدون آن عوض شود، یک ردیفِ دست‌کاری‌شده در دیتابیس
 *     بی‌سروصدا به رشته‌ی دیگری رمزگشایی می‌شود.
 *
 * بدون کلید، این تست **رد می‌شود نه شکست** — نصبی که رمزنگاری را روشن
 * نکرده کاملاً معتبر است.
 */

// ---------- نگهبان: فقط خط فرمان ----------
if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit('Not found.');
}

require_once __DIR__ . '/lib/assert.php';

if (file_exists(__DIR__ . '/../config/config.php')) {
    require_once __DIR__ . '/../config/config.php';
}
require_once __DIR__ . '/../includes/crypto.php';

T::group('رمزنگاریِ داده‌ی حساس');

// ---------- رفتار بدون کلید: هیچ چیز نباید بشکند ----------
// این را حتی وقتی کلید هست هم می‌شود سنجید، چون `decrypt` روی مقدارِ
// بی‌پیشوند همیشه خودِ ورودی را برمی‌گرداند.
T::same('6104337812345678', Crypto::decrypt('6104337812345678'),
    'مقدارِ خامِ قدیمی دست‌نخورده خوانده می‌شود');
T::same(null, Crypto::decrypt(null), 'null همان null می‌ماند');
T::same('',   Crypto::decrypt(''),   'رشته‌ی خالی همان می‌ماند');
T::same(null, Crypto::encrypt(null), 'رمز کردنِ null بی‌خطر است');
T::same('',   Crypto::encrypt(''),   'رمز کردنِ رشته‌ی خالی بی‌خطر است');

if (!Crypto::available()) {
    T::skip('رفت‌وبرگشت', 'کلید تنظیم نشده — رمزنگاری خاموش است');
    exit(T::report());
}

// ---------- رفت‌وبرگشت ----------
$samples = [
    '6104337812345678',
    '0203456789001',
    'IR120170000000123456789012',
    '۶۱۰۴۳۳۷۸۱۲۳۴۵۶۷۸',           // ارقام فارسی
    '1234 5678 9012 3456',          // با فاصله
    'a',                            // خیلی کوتاه
    str_repeat('9', 40),            // بلند
];
$bad = [];
foreach ($samples as $s) {
    $back = Crypto::decrypt(Crypto::encrypt($s));
    if ($back !== $s) { $bad[] = mb_substr($s, 0, 20) . ' → ' . var_export($back, true); }
}
T::bulk(count($samples), $bad, 'هر مقدار دقیقاً همان‌طور که بود برمی‌گردد');

// ---------- شکلِ ذخیره ----------
$c = Crypto::encrypt('6104337812345678');
T::ok(str_starts_with($c, Crypto::PREFIX), 'مقدارِ رمزشده پیشوندِ نسخه‌دار دارد', $c);
T::ok(!str_contains($c, '6104'), '⛔ متنِ اصلی در مقدارِ ذخیره‌شده دیده نمی‌شود');
T::ok(Crypto::isEncrypted($c) && !Crypto::isEncrypted('6104337812345678'),
    'تشخیصِ رمزشده از خام درست است');

// ---------- نانسِ تصادفی ----------
// ⚠ اگر نانس ثابت شود، دو حسابِ هم‌شماره مقدارِ ذخیره‌شده‌ی یکسان
//   می‌گیرند و از روی خودِ دیتابیس می‌شود فهمید کدام کاربران یک کارت
//   دارند — بی‌آنکه چیزی رمزگشایی شود.
T::ok(Crypto::encrypt('6104337812345678') !== Crypto::encrypt('6104337812345678'),
    'دو بار رمز کردنِ یک مقدار، دو خروجیِ متفاوت می‌دهد');

// ---------- دوباره رمز نشود ----------
T::same($c, Crypto::encrypt($c), 'مقدارِ از قبل رمزشده لایه‌ی دوم نمی‌گیرد');

// ---------- دست‌کاری گرفته می‌شود ----------
$raw = base64_decode(substr($c, strlen(Crypto::PREFIX)), true);
$tampered = $raw;
$tampered[strlen($tampered) - 1] = chr(ord($tampered[strlen($tampered) - 1]) ^ 0x01);
T::same(null, Crypto::decrypt(Crypto::PREFIX . base64_encode($tampered)),
    '⛔ ردیفِ دست‌کاری‌شده رمزگشایی نمی‌شود (نه اینکه رشته‌ی دیگری بدهد)');

T::same(null, Crypto::decrypt(Crypto::PREFIX . 'این base64 نیست!!'),
    'مقدارِ خرابِ رمزشده null می‌دهد، نه خطای کشنده');

// ---------- کلیدِ دیگر نباید بخواند ----------
// در یک پروسه‌ی جدا، چون کلید در ویژگیِ ایستا کش می‌شود.
$other = Crypto::newKey();
$code = 'define("APP_ENCRYPTION_KEY", $argv[2]);'
      . 'require "' . addslashes(__DIR__) . '/../includes/crypto.php";'
      . 'var_export(Crypto::decrypt($argv[1]));';
$out = trim((string)shell_exec(
    'php -r ' . escapeshellarg($code) . ' ' . escapeshellarg($c) . ' ' . escapeshellarg($other) . ' 2>/dev/null'
));
T::same('NULL', $out, '⛔ با کلیدِ دیگر رمزگشایی نمی‌شود');

// ---------- decryptRow ----------
$row = [
    'id' => 5,
    'card_number'    => Crypto::encrypt('6104337812345678'),
    'account_number' => null,
    'iban'           => '120170000000123456789012',   // خامِ قدیمی
    'name'           => 'بانک ملت',
];
$open = Crypto::decryptRow($row, Crypto::WALLET_FIELDS);
T::same('6104337812345678', $open['card_number'], 'decryptRow ستونِ رمزشده را باز می‌کند');
T::same('120170000000123456789012', $open['iban'], 'ستونِ خام را دست‌نخورده می‌گذارد');
T::same(null, $open['account_number'], 'ستونِ خالی خالی می‌ماند');
T::same('بانک ملت', $open['name'], 'ستون‌های دیگر دست نمی‌خورند');

// ---------- طولِ ستون کافی است ----------
// ⚠ اگر مقدارِ رمزشده از ستون بلندتر باشد، MySQL روی پیکربندیِ
//   غیر-strict آن را **بی‌صدا** می‌برد و رمزگشایی برای همیشه شکست
//   می‌خورد. طولِ ستون در migration_wallet_encrypt روی ۲۵۵ است.
$longest = 0;
foreach ([16, 19, 24, 26, 34, 40] as $n) {
    $longest = max($longest, strlen(Crypto::encrypt(str_repeat('9', $n))));
}
T::ok($longest <= 255,
    'بلندترین مقدارِ رمزشده در ستونِ ۲۵۵ جا می‌شود', "بیشترین: {$longest}");

exit(T::report());
