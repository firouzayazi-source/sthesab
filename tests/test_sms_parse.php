    $bad = [];
    foreach ($want as $k => $v) {
        $actual = $got[$k] ?? null;
        if ($actual !== $v) {
            $bad[] = "$k: انتظار " . var_export($v, true) . ' ولی ' . var_export($actual, true);
        }
    }
    T::ok($bad === [], $label, implode(' | ', $bad));
}

