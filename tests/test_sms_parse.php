        $label . ' — بدونِ تطبیقِ حساب');
}

// ⚠ وقتی خودکار نمی‌شود، **دلیلش** هم باید گفتنی باشد: پیامِ خالی یعنی
//   کاربر کلید را روشن کرده و نمی‌فهمد چرا گاهی کار می‌کند و گاهی نه.
foreach ($autoCases as $i => [$label, , $want]) {
    if ($want['with']) { continue; }
    T::ok(($res3[$i]['autoWithWallet']['why'] ?? '') !== '',
        "«{$label}» دلیلِ خودکار نشدن را می‌گوید");
}

$n = count($autoCases);
T::same($res3[$n]['fingerprint'], $res3[$n + 1]['fingerprint'],
    '⛔ فاصله و خطِ تازه اثرِ انگشت را عوض نمی‌کند');
T::same($res3[$n]['fingerprint'], $res3[$n + 2]['fingerprint'],
    '⛔ ارقامِ فارسی هم همان پیامک است، نه پیامکِ تازه');
T::ok($res3[$n]['fingerprint'] !== $res3[$n + 3]['fingerprint'],
    '⛔ ولی مبلغِ متفاوت یعنی پیامکِ متفاوت — وگرنه دو برداشتِ واقعی یکی شمرده می‌شدند');
T::ok(preg_match('/^[0-9a-f]{8}$/', (string)$res3[$n]['fingerprint']) === 1,
    'اثرِ انگشت هشت رقمِ شانزده‌شانزدهی است');

// ⛔ ورودیِ آشغال نباید **خطا** بدهد، باید «نه» بدهد.
//
//    این بررسی از یک جهشِ زنده‌مانده درآمد: با برداشتنِ شرطِ
//    `!r || !r.ok`، همه‌ی موردهای بالا همچنان سبز می‌ماندند چون
//    `parseBankSms` در شکست همه‌ی فیلدها را `null` می‌کند و شرط‌های
//    بعدی خودشان می‌گرفتندشان. تنها جایی که آن شرط واقعاً کار می‌کند
//    ورودیِ `null` است — و آنجا نبودش خطای کشنده می‌دهد، یعنی **کلِ
//    ثبتِ تراکنش** با یک پیامکِ عجیب می‌خوابد.
$probe = $res3[$n + 4] ?? [];

// ⛔ پیش‌فرضِ کلید **خاموش** است، و این قابل مذاکره نیست: روشن شدنش با
//    یک به‌روزرسانی یعنی اپ بی‌آنکه کسی خواسته باشد شروع کند به نوشتن
//    در دفترِ مالیِ کاربر. در sandbox هیچ چیزی در localStorage نیست،
//    یعنی دقیقاً حالتِ «کاربر هیچ‌وقت روشنش نکرده».
T::same(false, $probe['autoDefault'] ?? null,
    '⛔ ثبتِ خودکار پیش‌فرض خاموش است');

foreach (['junkNull' => 'null', 'junkUndef' => 'undefined', 'junkEmpty' => 'شیِ خالی'] as $k => $lbl) {
    T::same(false, $probe[$k]['ok'] ?? null,
        "ورودیِ {$lbl} «نه» می‌گیرد، نه خطا",
        'why: ' . ($probe[$k]['why'] ?? '—'));
}

exit(T::report());
