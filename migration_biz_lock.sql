-- ============================================================
-- محیطِ فروشگاهی — بستنِ دوره (قفلِ تاریخ)
-- ============================================================
--
-- **خواسته‌ی مالکِ نصب:** «بساز دوتاشو» — بستنِ دوره و چکِ خرجی، بعد از
-- بررسیِ حسابداریِ فروشگاه.
--
-- ⛔ `lock_date` = آخرین روزِ بسته: هیچ سندی با تاریخِ **تا همین روز** صادر،
--    باطل، به پیش‌نویس برگردانده یا تازه ثبت نمی‌شود (فاکتور، برگشت، دریافت و
--    پرداخت، وصول و برگشتِ چک، انبارگردانی، موجودی و مانده‌ی اول دوره). پس
--    سود، بهای تمام‌شده و مانده‌ی ماهِ بسته دیگر با هیچ سندِ تاریخ‌گذشته‌ای
--    تکان نمی‌خورد. تنها مرجعِ سنجش `Biz::lockError()` است.
-- `NULL` = هیچ دوره‌ای بسته نیست (پیش‌فرض؛ هیچ نصبی با به‌روزرسانی رفتارش
-- عوض نمی‌شود). ایدمپوتنت. چکِ خرجی ستونِ تازه نمی‌خواهد: وضعیتِ `endorsed`
-- در همان `cheque_status` (VARCHAR(10)) و پیوند در همان `cheque_settle_id`.

ALTER TABLE `biz_settings`
    ADD COLUMN IF NOT EXISTS `lock_date` DATE NULL DEFAULT NULL
        COMMENT 'آخرین روزِ دوره‌ی بسته — Biz::lockError()';
