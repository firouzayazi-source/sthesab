-- «کدام حساب روی صفحه‌ی خانه دیده شود؟»
--
-- ⛔ چرا ستونِ دیتابیس و نه `localStorage`:
--    فیلترِ اقلامِ صفحه‌ی دارایی (`daftar_asset_off`) عمداً در مرورگر
--    می‌ماند، چون یک **نگاه** است نه داده. ولی «این حساب را روی خانه
--    می‌خواهم» یک تصمیمِ ماندگار درباره‌ی خودِ حساب است — مثل
--    `sort_order` و `color`. اگر در مرورگر می‌ماند، کاربری که گوشی و
--    لپ‌تاپ دارد دو خانه‌ی متفاوت می‌دید و پاک کردنِ داده‌ی سایت
--    انتخابش را می‌برد.
--
-- ⚠ روی خودِ `wallets` است، پس با حذفِ حساب خودبه‌خود می‌رود و هیچ
--   ردیفِ یتیمی نمی‌ماند.
--
-- ⛔ پیش‌فرض ۰ و این عمدی است: هیچ نصبِ موجودی نباید بعد از یک
--    `git pull` صفحه‌ی خانه‌اش عوض شود. نوار تا وقتی کاربر خودش چیزی
--    پین نکند اصلاً رندر نمی‌شود.
ALTER TABLE `wallets`
    ADD COLUMN IF NOT EXISTS `pinned` TINYINT(1) NOT NULL DEFAULT 0
        COMMENT 'روی صفحه‌ی خانه دیده شود' AFTER `sort_order`;
