-- ============================================================
-- migration_more_categories.sql — شش دسته‌ی هزینه‌ی جاافتاده
-- ============================================================
--
-- از فهرستِ یک اپِ حسابداریِ ایرانیِ دیگر برداشته شده، ولی **همه‌اش
-- نه**. چیزهایی که واقعاً در دفترِ یک خانواده‌ی ایرانی خرج می‌شوند و
-- ما نداشتیم:
--
--   خودرو            بنزین، تعمیر، جریمه، عوارض — سطلی جدا از
--                    «حمل‌ونقل» که تاکسی و مترو است. کسی که ماشین
--                    دارد بزرگ‌ترین هزینه‌ی متغیرش همین است.
--   بیمه             ثالث، بدنه، عمر، تکمیلی. سالانه است، پس دقیقاً
--                    همان چیزی که یادش می‌رود و بعد یک‌جا می‌خورد.
--   دیون مذهبی       خمس، زکات، صدقه. هیچ اپِ خارجی‌ای این را ندارد
--                    و برای بخشِ بزرگی از کاربرِ ایرانی یک قلمِ
--                    برنامه‌ریزی‌شده‌ی واقعی است.
--   مالیات و عوارض   مالیات، عوارض شهرداری، عوارض خروج از کشور.
--   کارمزد و سود بانکی  کارمزد انتقال، سود وام، هزینه‌ی صدور کارت.
--   جریمه و دیرکرد   دیرکردِ قسط، جریمه‌ی رانندگی. جدا از «قسط و وام»
--                    چون خودِ قسط هزینه‌ی برنامه‌ریزی‌شده است و جریمه
--                    نه — و دیدنِ جداشان همان چیزی است که رفتار را
--                    عوض می‌کند.
--
-- ⛔ «سرمایه‌گذاری» عمداً **نیامد**، با اینکه در آن فهرست زیرِ هزینه‌ها
--    بود. خریدِ طلا یا سهام هزینه نیست؛ پول از یک شکل به شکلِ دیگر
--    می‌رود. اگر هزینه حسابش کنیم، گزارشِ هزینه‌ی کاربر دروغ می‌گوید و
--    «پول قابل خرج» بی‌دلیل کم می‌شود. این اپ از قبل جای درستش را
--    دارد: دارایی، معاملات، و خالص دارایی.
--    «هزینه‌های اداری» هم نیامد — آن فهرست برای کسب‌وکار است، نه خانه.
--
-- ⛔ محافظ: یک نشانه در `app_settings` گذاشته می‌شود و اگر باشد این
--    فایل هیچ کاری نمی‌کند. دلیلش این نیست که ایدمپوتنت شود (شرطِ
--    `LEFT JOIN` خودش آن را تضمین می‌کند) بلکه این است که اگر کاربر
--    یکی از این دسته‌ها را **عمداً حذف کند**، اجرای بعدی دوباره
--    زنده‌اش نکند. بدونِ نشانه، هر deploy کارِ کاربر را پس می‌زد.
--
-- ⚠ دسته‌های شخصیِ کاربران (`user_id` عددی) اصلاً دیده نمی‌شوند؛ فقط
--   پیش‌فرض‌های برنامه (`user_id IS NULL`).
--
-- ایدمپوتنت است.

SET @already_seeded := (
    SELECT COUNT(*) FROM `app_settings` WHERE `setting_key` = 'more_categories_seeded'
);

-- ⛔ جدولِ موقت با **همان collation** جدولِ اصلی ساخته می‌شود.
--    اگر با collation پیش‌فرضِ اتصال ساخته شود، `JOIN` روی `name`
--    دو ستونِ هم‌قابلیت را مقایسه می‌کند و با
--    «Illegal mix of collations» می‌میرد — همان چیزی که یک بار
--    `FIND_IN_SET(name, @var)` را روی سرور کشت. اینجا رشته‌ی ثابت
--    نداریم که خودش تبدیل شود، پس باید صریح باشد.
DROP TEMPORARY TABLE IF EXISTS `_cat_seed`;
CREATE TEMPORARY TABLE `_cat_seed` (
    `name`  VARCHAR(100) NOT NULL,
    `icon`  VARCHAR(24)  NOT NULL,
    `color` VARCHAR(7)   NOT NULL
) ENGINE=Memory DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_persian_ci;

INSERT INTO `_cat_seed` (`name`, `icon`, `color`) VALUES
    ('خودرو',              'car',     '#b45309'),
    ('بیمه',               'shield',  '#0891b2'),
    ('دیون مذهبی',         'gift',    '#059669'),
    ('مالیات و عوارض',     'bill',    '#64748b'),
    ('کارمزد و سود بانکی', 'money',   '#7c3aed'),
    ('جریمه و دیرکرد',     'repair',  '#dc2626');

INSERT INTO `categories` (`user_id`, `name`, `type`, `icon`, `color`, `is_active`)
SELECT NULL, s.`name`, 'expense', s.`icon`, s.`color`, 1
FROM `_cat_seed` s
LEFT JOIN `categories` c
       ON c.`name` = s.`name` AND c.`user_id` IS NULL
WHERE c.`id` IS NULL
  AND @already_seeded = 0;

DROP TEMPORARY TABLE IF EXISTS `_cat_seed`;

-- نشانه: از این به بعد این فایل کاری نمی‌کند، حتی اگر کاربر یکی از
-- دسته‌ها را حذف کرده باشد.
INSERT INTO `app_settings` (`setting_key`, `setting_value`)
VALUES ('more_categories_seeded', '1')
ON DUPLICATE KEY UPDATE `setting_value` = '1';

SELECT 'migration_more_categories با موفقیت اجرا شد.' AS result;
