-- دو نشانه‌ی تک‌ردیفی روی خودِ کاربر: «دقیقه‌ی اول» و «پشتیبانِ کاربر».
--
-- ⛔ `balance_setup_at` — چرا لازم است:
--    حسابِ پیش‌فرضِ هر کاربرِ تازه با `initial_balance = 0` ساخته می‌شود
--    (`createUserAccount()`), و هیچ‌جای اپ به او نمی‌گوید موجودیِ واقعی‌اش
--    را وارد کند. نتیجه این است که با اولین هزینه، «مجموع حساب‌ها» منفی
--    می‌شود و «پول قابل خرج» تا ابد منفی می‌ماند — یعنی تنها عددی که به
--    کارِ کاربر می‌آید، از روزِ اول دروغ می‌گوید. خرابیِ کاملاً بی‌صدا:
--    هیچ خطایی نیست، فقط کاربر نتیجه می‌گیرد اپ خراب است.
--
--    ⚠ و **نبودِ ستون شرطِ کافی نیست**: کاربری که واقعاً موجودی‌اش صفر
--      است، با شرطِ «همه‌ی حساب‌ها صفرند» تا ابد همان کارت را می‌دید.
--      پس یک نشانه‌ی صریح لازم است که هم با تنظیم کردن پر شود هم با
--      «نیازی نیست».
--
-- ⛔ `last_backup_at` — چرا لازم است:
--    `backup.php` از قبل هست و کار می‌کند، ولی هیچ‌کس بی‌یادآوری بکاپ
--    نمی‌گیرد. دفتری که کاربر سه سال نگه داشته، اگر یک بار از دست برود
--    رابطه تمام است. با این ستون، `Notify` ماهی یک بار یادآوری می‌کند و
--    کسی که تازه بکاپ گرفته یادآوری نمی‌گیرد.
--
-- ⚠ هر دو `NULL` می‌مانند برای کاربرانِ موجود، یعنی «هنوز تصمیم نگرفته» —
--   همان قاعده‌ی `notification_prefs`. مقدارِ پیش‌فرضِ صفر یا امروز، این
--   تفاوت را از بین می‌برد.
ALTER TABLE `users`
    ADD COLUMN IF NOT EXISTS `balance_setup_at` DATETIME NULL DEFAULT NULL
        COMMENT 'کِی موجودی اولیه تنظیم یا رد شد؛ NULL = هنوز پرسیده نشده',
    ADD COLUMN IF NOT EXISTS `last_backup_at` DATETIME NULL DEFAULT NULL
        COMMENT 'آخرین خروجیِ کاملِ داده؛ NULL = هرگز';
