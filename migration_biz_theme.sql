-- ============================================================
-- محیطِ فروشگاهی — رنگِ فروشگاه (پالت)
-- ============================================================
--
-- **خواسته‌ی مالکِ نصب:** «در بخشِ فروشگاهی هم همین استایل کار کن» — منوی
-- کناریِ طیف‌دار که با رنگِ انتخاب‌شده عوض می‌شود، مثلِ حساب لند.
--
-- ⛔ روی `biz_settings` است، نه `localStorage` (برخلافِ پالتِ شخصی):
--    رنگِ فروشگاه تصمیمِ **خودِ فروشگاه** است (مثلِ سربرگِ فاکتور)، پس روی
--    هر دستگاه یکی است و سرور همان را روی `<html>` رندر می‌کند — نه
--    اسکریپتی لازم است، نه چشمکی از رنگِ پیش‌فرض.
-- `NULL` یعنی پیش‌فرض (اولین کلیدِ `Biz::PALETTES`)؛ پس پیش‌فرضِ فردا به همه
-- می‌رسد. کلیدِ ناشناخته هنگامِ خواندن به پیش‌فرض برمی‌گردد. ایدمپوتنت.

ALTER TABLE `biz_settings`
    ADD COLUMN IF NOT EXISTS `palette` VARCHAR(12) NULL DEFAULT NULL
        COMMENT 'رنگِ فروشگاه — Biz::palette()';
