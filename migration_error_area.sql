-- «خطاهای فروشگاه» — هر خطا می‌گوید از کدام محیط آمده.
--
-- **خواسته‌ی مالکِ نصب:** «یک سیستم لاگ برای باگ در فروشگاهم بیاد — الان
-- در حساب‌لند داریم — البته فقط برای سوپر ادمین.»
--
-- ⛔ ستونِ محیط است، نه جدولِ دوم. خطای فروشگاه و حساب‌لند از **همان**
--    کد می‌آیند (`includes/` مشترک است)، پس جدولِ جدا یعنی دو ثبت‌کننده،
--    دو «برطرف شد» و دو نشان — و خطایی که در یکی بسته شده در دیگری باز
--    می‌ماند. با یک ستون، `admin/errors.php` همه را می‌بیند و
--    `store/errors.php` فقط فروشگاه را.
--
-- ⚠ محیط از **مسیرِ درخواست** می‌آید (`store/…`)، نه از فایلِ خطا:
--   خطای `includes/functions.php` روی صفحه‌ی فروشگاه، خطای فروشگاه است.
--   و خطای مرورگر محیط را خودش می‌فرستد (فهرستِ بسته، `AppErrors::AREAS`).
--
-- ⛔ و همچنان هیچ `user_id` یا آدرسی نیست — «کدام محیط» درباره‌ی کد است،
--    نه درباره‌ی کاربر (بالای `includes/app_errors.php`).
--
-- پیش‌فرض `app` است، پس هر ردیفِ موجود «حساب‌لند» دیده می‌شود — که درست
-- است: پیش از این، فروشگاه هیچ خطای مرورگری نمی‌فرستاد.
ALTER TABLE `app_errors`
    ADD COLUMN IF NOT EXISTS `area` VARCHAR(8) NOT NULL DEFAULT 'app'
        COMMENT 'app = حساب‌لند، store = فروشگاه (AppErrors::AREAS)'
        AFTER `level`;

-- نشانِ نوارِ فروشگاه یک `COUNT` روی «بازهای این محیط» است، روی هر صفحه‌ی
-- فروشگاهِ مدیر.
ALTER TABLE `app_errors`
    ADD INDEX IF NOT EXISTS `idx_area_open` (`area`, `resolved_at`, `last_seen`);
