-- ============================================================
-- دسته‌بندی‌های پیش‌فرضِ خانوار به‌جای فهرستِ مغازه
-- ============================================================
--
-- ⛔ چرا: دسته‌های پیش‌فرضِ اولیه فهرستِ یک مغازه‌ی موبایل بود —
--    «فروش گوشی»، «فروش لوازم جانبی»، «تبلیغات»، «خرید کالا» و بدتر از
--    همه «حقوق» به‌عنوان **هزینه**. برای یک اپ مالیِ شخصی و خانوادگی
--    این یعنی اولین منویی که کاربر در شیت ثبت باز می‌کند هیچ ربطی به
--    زندگی‌اش ندارد: نه خوراک، نه قبوض، نه درمان، نه قسط — و «حقوق»،
--    که درآمدِ اصلیِ اغلب خانواده‌هاست، اصلاً در فهرستِ درآمد نبود.
--
-- ⛔ محافظِ اصلی: این migration **فقط** وقتی کاری می‌کند که فهرستِ
--    پیش‌فرض دقیقاً همان seedِ دست‌نخورده‌ی مغازه باشد. اگر مالکِ نصب
--    حتی یکی از آن‌ها را عوض کرده، حذف کرده، یا دسته‌ی تازه‌ای ساخته
--    باشد، هیچ چیز عوض نمی‌شود. دلیلش روشن است: این دسته‌ها به
--    تراکنش‌های واقعی چسبیده‌اند و جابه‌جا کردنشان یعنی خراب کردنِ
--    تاریخچه‌ی مالیِ کسی که سال‌ها از اپ استفاده کرده.
--
-- ⚠ دسته‌های شخصیِ کاربران (`user_id` عددی) اصلاً دیده نمی‌شوند؛ این
--   فایل فقط با پیش‌فرض‌های برنامه (`user_id IS NULL`) کار دارد.
--   «سود معاملات» و «زیان معاملات» هم دست‌نخورده می‌مانند چون
--   syncTradeProfitTransactions به نامشان وابسته است.
--
-- ایدمپوتنت است: اجرای دوباره هیچ اثری ندارد.

-- ---------- ۱. آیا seedِ دست‌نخوردهٔ مغازه است؟ ----------
-- شرط: دقیقاً همان ۱۱ نام، نه یکی بیشتر نه یکی کمتر (به‌جز دو دسته‌ی
-- معاملات که برنامه خودش بعداً می‌سازد).
--
-- ⛔ فهرست عمداً به‌شکلِ `IN (...)` با رشته‌های ثابت نوشته شده، نه
--    `FIND_IN_SET(name, @vars)`. یک متغیرِ کاربری همان «قابلیتِ تبدیلِ
--    ۲» را دارد که یک ستون دارد، پس روی دیتابیسی که ستونش
--    `utf8mb4_persian_ci` است و اتصالش `utf8mb4_general_ci`، مقایسه با
--    خطای «Illegal mix of collations» می‌میرد. رشته‌ی ثابت قابلیتِ ۴
--    دارد و همیشه به collation ستون تبدیل می‌شود.
--    روی سرور واقعی همین اتفاق افتاد و migration وسطِ کار ایستاد.

SET @defaults_total := (
    SELECT COUNT(*) FROM `categories`
    WHERE `user_id` IS NULL AND `name` NOT IN ('سود معاملات', 'زیان معاملات')
);

SET @shop_matched := (
    SELECT COUNT(*) FROM `categories`
    WHERE `user_id` IS NULL
      AND `name` IN ('فروش گوشی', 'خدمات', 'فروش لوازم جانبی', 'سایر درآمدها',
                     'خرید کالا', 'اجاره', 'حقوق', 'تبلیغات', 'حمل‌ونقل',
                     'قبوض', 'سایر هزینه‌ها')
);

-- ۱۱ تا از ۱۱ تا، و هیچ دسته‌ی پیش‌فرضِ دیگری وجود نداشته باشد.
SET @is_pristine_shop := (@defaults_total = 11 AND @shop_matched = 11);

-- ---------- ۲. آیا اصلاً به تراکنشی چسبیده‌اند؟ ----------
-- حتی اگر نام‌ها دست‌نخورده باشند، ممکن است کاربر با همان‌ها ماه‌ها
-- تراکنش ثبت کرده باشد. آن‌وقت حذفشان تاریخچه را بی‌دسته می‌کند
-- (`ON DELETE SET NULL`). پس فقط وقتی جایگزین می‌کنیم که هیچ‌کدام
-- استفاده نشده باشند؛ در غیر این صورت دسته‌های خانوار **کنارشان**
-- اضافه می‌شوند و قدیمی‌ها فقط غیرفعال می‌شوند.
SET @shop_used := (
    SELECT COUNT(*) FROM `transactions` t
    JOIN `categories` c ON c.id = t.category_id
    WHERE c.user_id IS NULL
      AND c.name IN ('فروش گوشی', 'خدمات', 'فروش لوازم جانبی', 'سایر درآمدها',
                     'خرید کالا', 'اجاره', 'حقوق', 'تبلیغات', 'حمل‌ونقل',
                     'قبوض', 'سایر هزینه‌ها')
);

-- ---------- ۳. «حقوق» اول اصلاح شود، بعد درج ----------
-- در seedِ قدیمی «حقوق» به‌اشتباه `expense` بود (دستمزدِ کارمندِ مغازه)
-- و در فهرستِ خانوار `income` است. این ردیف باید **اصلاح** شود نه حذف،
-- وگرنه هم دسته‌ی مفیدی از دست می‌رود هم تراکنش‌های چسبیده به آن.
--
-- ⛔ و این UPDATE باید **پیش از** INSERT بیاید. اولین نسخه بعدش بود و
--    نتیجه دو ردیفِ «حقوق»ِ درآمد شد: هنگام INSERT، شرطِ NOT EXISTS
--    دنبال «حقوق» با نوع income می‌گشت و ردیفِ قدیمی هنوز expense بود،
--    پس رد می‌شد و یکی تازه درج می‌کرد؛ بعد UPDATE قدیمی را هم income
--    می‌کرد. روی دیتابیس واقعی آزموده و دیده شد.
UPDATE `categories`
SET `type` = 'income', `icon` = 'salary', `color` = '#059669'
WHERE @is_pristine_shop = 1
  AND `user_id` IS NULL AND `name` = 'حقوق' AND `type` = 'expense';

-- ---------- ۴. افزودنِ دسته‌های خانوار ----------
-- در هر حالتی (چه seed دست‌نخورده باشد چه نه) این‌ها فقط وقتی درج
-- می‌شوند که هم‌نامشان از قبل نباشد. `INSERT ... SELECT ... WHERE NOT
-- EXISTS` به‌ازای هر ردیف، پس اجرای دوباره چیزی اضافه نمی‌کند.
INSERT INTO `categories` (`user_id`, `name`, `type`, `icon`, `color`, `is_active`)
SELECT NULL, s.n, s.t, s.i, s.c, 1
FROM (
    SELECT 'حقوق' AS n, 'income' AS t, 'salary' AS i, '#059669' AS c
    UNION ALL SELECT 'پاداش و عیدی',    'income',  'gift',      '#a855f7'
    UNION ALL SELECT 'درآمد آزاد',      'income',  'money',     '#10b981'
    UNION ALL SELECT 'سود سپرده',       'income',  'profit',    '#16a34a'
    UNION ALL SELECT 'اجاره‌ی دریافتی', 'income',  'home',      '#0d9488'
    UNION ALL SELECT 'خوراک',           'expense', 'food',      '#f97316'
    UNION ALL SELECT 'مسکن و اجاره',    'expense', 'home',      '#ef4444'
    UNION ALL SELECT 'قبوض',            'expense', 'bill',      '#eab308'
    UNION ALL SELECT 'حمل‌ونقل',        'expense', 'transport', '#0ea5e9'
    UNION ALL SELECT 'موبایل و اینترنت','expense', 'phone',     '#06b6d4'
    UNION ALL SELECT 'درمان',           'expense', 'health',    '#ec4899'
    UNION ALL SELECT 'پوشاک',           'expense', 'clothes',   '#f43f5e'
    UNION ALL SELECT 'آموزش',           'expense', 'education', '#6366f1'
    UNION ALL SELECT 'قسط و وام',       'expense', 'money',     '#64748b'
    UNION ALL SELECT 'تفریح و سفر',     'expense', 'fun',       '#d946ef'
    UNION ALL SELECT 'هدیه و مهمانی',   'expense', 'gift',      '#a855f7'
) AS s
WHERE @is_pristine_shop = 1
  AND NOT EXISTS (
      SELECT 1 FROM `categories` c2
      WHERE c2.user_id IS NULL AND c2.name = s.n AND c2.type = s.t
  );

-- ---------- ۵. برداشتنِ دسته‌های مغازه ----------
-- «حقوق» اینجا نیست چون در مرحله‌ی ۳ اصلاح شد، نه حذف.
-- اگر هیچ تراکنشی به آن‌ها وصل نیست، پاک می‌شوند.
DELETE FROM `categories`
WHERE @is_pristine_shop = 1 AND @shop_used = 0
  AND `user_id` IS NULL
  AND `name` IN ('فروش گوشی', 'خدمات', 'فروش لوازم جانبی',
                 'خرید کالا', 'اجاره', 'تبلیغات');

-- اگر تراکنش دارند، فقط از منوها بیرون می‌روند و تاریخچه سالم می‌ماند.
UPDATE `categories`
SET `is_active` = 0
WHERE @is_pristine_shop = 1 AND @shop_used > 0
  AND `user_id` IS NULL
  AND `name` IN ('فروش گوشی', 'خدمات', 'فروش لوازم جانبی',
                 'خرید کالا', 'اجاره', 'تبلیغات');
