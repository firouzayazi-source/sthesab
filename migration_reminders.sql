-- ============================================================
-- یادآوریِ سررسید — تنظیمات هر کاربر
-- ============================================================
--
-- ⛔ چرا این مهم‌ترین قابلیتِ نبودِ اپ بود: هسته‌ی این برنامه سررسید
--    است — چک، طلب و بدهی، تراکنش دوره‌ای. ولی اپ فقط وقتی حرف می‌زد
--    که کاربر خودش بازش کند؛ یعنی دقیقاً همان لحظه‌ای که دیگر یادآوری
--    لازم ندارد. چکِ برگشتی عارضه‌ی حقوقی دارد و بدهیِ دیرکرد رابطه‌ی
--    خانوادگی را خراب می‌کند.
--
-- ⚠ ستون‌ها روی خودِ users نمی‌نشینند بلکه جدولِ جدا دارند، چون
--   ردیفِ نبودن = «هنوز تصمیم نگرفته» و با پیش‌فرضِ کد پر می‌شود.
--   اگر ستون بود، باید برای همه‌ی کاربرانِ موجود یک پیش‌فرض می‌نوشتیم
--   و بعد نمی‌شد «انتخاب نکرده» را از «خاموش گذاشته» تشخیص داد.
--
-- ⛔ پیش‌فرض عمداً **روشن** است (`email_on = 1`). این تنها قابلیتی
--    است که ارزشش در نبودنش دیده نمی‌شود: کاربری که نمی‌داند وجود
--    دارد هرگز روشنش نمی‌کند، و بعد چکش برگشت می‌خورد. ولی فقط برای
--    کسی می‌فرستد که ایمیل ثبت کرده باشد و سررسیدی داشته باشد، پس
--    هیچ‌کس ایمیلِ بی‌ربط نمی‌گیرد.
--
-- ایدمپوتنت است.

CREATE TABLE IF NOT EXISTS `notification_prefs` (
    `user_id`      INT UNSIGNED NOT NULL,
    `email_on`     TINYINT(1) NOT NULL DEFAULT 1,
    `days_before`  TINYINT UNSIGNED NOT NULL DEFAULT 3,
    -- آخرین روزی که برای این کاربر ایمیل رفته. جلوی ارسالِ دوباره در
    -- یک روز را می‌گیرد: اگر cron دو بار اجرا شود یا دستی صدایش بزنند،
    -- کاربر دو ایمیل نمی‌گیرد.
    `last_sent_on` DATE DEFAULT NULL,
    `created_at`   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at`   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`user_id`),
    CONSTRAINT `fk_notif_prefs_user` FOREIGN KEY (`user_id`)
        REFERENCES `users` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_persian_ci;
