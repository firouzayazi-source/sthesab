-- ============================================================
-- پیامکِ بانک: «یک بار بپرس، بعد خودکار» — حسابی که کاربر انتخاب کرد یاد گرفته می‌شود
-- ============================================================
--
-- **گزارشِ مالکِ نصب (مهر ۱۴۰۵):** «پیامک‌های بلو رو نخونده … مگه نباید بعد
-- از پیامک بپرسه از چه حسابی برداشت یا به چه حسابی واریز شده و از دفعه بعد
-- خودش وارد اون حساب کنه و از همون حساب موجودی کم کنه؟»
--
-- پیامکِ بلو (و خیلی از بانک‌ها) نه شماره‌ی کارت دارد نه شماره‌ی حساب، پس
-- `smsMatchWallet()` حسابی پیدا نمی‌کرد و هر بار برای بررسی می‌ماند. حالا
-- وقتی کاربر یک بار حساب را برای چنین پیامکی انتخاب کند، نشانه‌های همان
-- پیامک روی همان حساب می‌نشیند (`SmsSync::learn()`) و پیامکِ بعدی خودکار.
--
-- ⛔ **متنِ پیامک ذخیره نمی‌شود**: هر نشانه یا چهار رقمِ آخرِ کارت/حساب است
--    (همان که `walletSmsKeys()` از قبل به صفحه می‌دهد) یا اثرِ انگشتِ هشت‌رقمیِ
--    خطِ نامِ فرستنده (`s` + FNV-1a)، نه خودِ متن.
--
-- ایدمپوتنت. شاهد: `wallets.sms_keys`.

ALTER TABLE `wallets`
    ADD COLUMN IF NOT EXISTS `sms_keys` VARCHAR(255) NULL DEFAULT NULL
        COMMENT 'نشانه‌های یادگرفته‌ی پیامک (c1234,a5678,s0a1b2c3d) — SmsSync::learn';
