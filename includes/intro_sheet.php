 *    اسلایدِ دوم را می‌بندد یعنی «نمی‌خواهم»؛ اگر فقط اسلایدِ آخر
 *    نشانه‌گذاری می‌کرد، همان آدم دفعه‌ی بعد دوباره همین را می‌دید و
