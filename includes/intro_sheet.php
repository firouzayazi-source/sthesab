 * معرفیِ اولیه — یک تورِ نورافکنی روی خودِ صفحه، نه یک جعبه‌ی وسطِ صفحه.
 *
 * **گزارشِ مالکِ نصب:** «معرفی اولیه که کاربر از اپ می‌بینه خوشگل‌تر و
