 *    دیر یا زود از اصل دور می‌افتد: `display: none`ِ پیش‌فرض (پس هیچ
 *    ویژگیِ `hidden` ای رندر نمی‌شود و قاعده ۱۸ موضوعیت ندارد)،
 *    قفلِ بدنه در `watchOverlays()`، و همان `z-index` ای که بقیه‌ی
 *    لایه‌ها دارند.
 *    ⚠ ولی `padding`ِ حاشیه‌ی امنِ آن کلاس را `.intro-overlay` صفر
 *      می‌کند (تمام‌صفحه یعنی تمام‌صفحه)، پس **خودِ کارت** باید
 *      `env(safe-area-inset-*)` داشته باشد — وگرنه دقیقاً همان خرابی
 *      برمی‌گردد که قاعده ۱۳ برای گرفتنش نوشته شد. قاعده ۴۷ این را
 *      جدا می‌سنجد.
 *
 * ⛔ **تنها مرجعِ اسلایدها همین آرایه است** — هم متن، هم نقطه‌ها، و هم
 *    **هدفِ نورافکن**. با یک فهرستِ دومِ جاوااسکریپتی، اولین باری که
 *    یک انتخابگر عوض شود نورافکن بی‌صدا روی هیچ می‌نشیند و کاربر یک
 *    حفره‌ی خالی وسطِ صفحه می‌بیند — همان قاعده‌ی `Auth::SESSION_WINDOWS`
 *    و `DUE_TABS`.
 *
 * ⛔ **`target` یک فهرستِ نامزد است، نه یک انتخابگرِ تکی**، و `app.js`
 *    **اولین نامزدِ دیده‌شدنی** را برمی‌دارد. دلیلش این است که همین اپ
 *    روی موبایل و دسکتاپ دو چیدمانِ متفاوت دارد: دکمه‌ی ثبت روی موبایل
 *    `#addTxBtn`ِ نوارِ پایین است و روی دسکتاپ قلمِ نوارِ کناری
 *    (`.bottom-nav` بالای ۹۰۰ پیکسل `display: none` می‌شود). با یک
 *    انتخابگرِ ثابت، نورافکن روی یکی از آن دو **هیچ‌وقت** چیزی پیدا
 *    نمی‌کرد — و آن همان «روی گوشی درست است» ای است که این پروژه بارها
 *    نوشته مدرک نیست.
 *
 * ⚠ متن‌ها عمداً درباره‌ی **کاری که کاربر می‌کند** حرف می‌زنند، نه
 *   درباره‌ی «امکانات». فهرستِ امکانات چیزی است که کاربر ردش می‌کند.
