-- «برطرف شد» برای یک خطا — به‌جای پاک کردنِ کلِ فهرست.
--
-- ⛔ مسئله‌ی واقعی، و مالکِ نصب گزارشش کرد: تنها اقدامِ ممکن روی فهرستِ
--    خطاها `پاک کردن فهرست` بود، یعنی **همه یا هیچ**. کسی که یک خطا را
--    رفع کرده ناچار بود کلِ تاریخچه را پاک کند — از جمله خطاهایی که
--    هنوز ندیده بود. نتیجه در عمل: هیچ‌کس دست نمی‌زد و فهرست به‌مرور
--    پر از چیزهای رفع‌شده می‌شد و **خطای تازه در آن گم می‌شد**.
--
-- ⛔ و «برطرف شد» با «حذف» یکی نیست، و همین کلِ نکته است: اگر همان خطا
--    **دوباره** رخ دهد، `AppErrors::record()` این ستون را `NULL`
--    می‌کند و خطا برمی‌گردد. وگرنه «برطرف شد» به «برای همیشه ساکت» بدل
--    می‌شد — یعنی دقیقاً همان خرابیِ بی‌صدایی که این جدول برای دیدنش
--    ساخته شده، فقط این بار با دستِ خودمان.
--
-- ⚠ NULL = باز (رسیدگی نشده). پس نصب‌های موجود بعد از این migration
--   همه‌ی خطاهایشان را «باز» می‌بینند، که درست است: هیچ‌کدام رسیدگی
--   نشده‌اند.
--
-- ایندکس روی `(resolved_at, last_seen)` است چون کوئریِ همیشگیِ این
-- جدول «خطاهای بازِ تازه» است (`WHERE resolved_at IS NULL ORDER BY
-- last_seen DESC`) و نشانِ نوارِ مدیر هم یک `COUNT` روی همان شرط است —
-- روی **هر** صفحه‌ی `admin/`.
ALTER TABLE `app_errors`
    ADD COLUMN IF NOT EXISTS `resolved_at` DATETIME NULL DEFAULT NULL
        COMMENT 'NULL = باز؛ با رخدادِ دوباره خودبه‌خود NULL می‌شود'
        AFTER `hits`;

ALTER TABLE `app_errors`
    ADD INDEX IF NOT EXISTS `idx_open` (`resolved_at`, `last_seen`);
