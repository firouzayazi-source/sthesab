-- ============================================================
-- migration_login_throttle.sql — محدودیت تلاش ناموفق ورود
--
-- تا پیش از این، صفحه‌ی ورود هیچ سدی در برابر حدس رمز نداشت: نه شمارش
-- تلاش ناموفق، نه قفل موقت، نه تأخیر. یعنی می‌شد بی‌نهایت رمز امتحان
-- کرد. نکته‌ی عجیب اینکه *بازیابی* رمز محدودیت داشت (۳ بار برای هر
-- کاربر، ۱۰ بار برای هر IP) ولی خود ورود نداشت — در پشتی محکم بود و
-- در جلویی باز.
--
-- طراحی عمداً ساده است: هر تلاش ناموفق یک ردیف می‌شود، و هر دو کلیدِ
-- «نام کاربریِ واردشده» و «IP» جدا شمرده می‌شوند. تلاش موفق ردیف‌های
-- همان نام کاربری را پاک می‌کند، پس کاربری که رمزش را چند بار غلط زده
-- ولی بالاخره درست وارد شده، دفعه‌ی بعد از صفر شروع می‌کند.
--
-- چرا هر دو کلید: فقط IP کافی نیست چون مهاجم از چند IP می‌آید؛ فقط نام
-- کاربری هم کافی نیست چون آن‌وقت مهاجم می‌تواند با تلاش عمدی، حساب یک
-- نفر دیگر را قفل کند (denial of service). با هر دو، حمله‌ی پخش‌شده
-- روی یک حساب و حمله‌ی متمرکز از یک IP هر دو گرفته می‌شوند.
--
-- `username_tried` عمداً به `users` وصل نیست: تلاش روی نام کاربریِ
-- ناموجود هم باید شمرده شود، وگرنه مهاجم می‌تواند با نام‌های تصادفی
-- بی‌نهایت درخواست بزند. به همین دلیل کلید خارجی هم ندارد.
--
-- ایمن برای اجرای دوباره.
-- ============================================================

CREATE TABLE IF NOT EXISTS `login_attempts` (
    `id`             INT UNSIGNED NOT NULL AUTO_INCREMENT,
    `username_tried` VARCHAR(190) NOT NULL COMMENT 'همان چیزی که در فرم وارد شد؛ ممکن است اصلاً کاربر نباشد',
    `request_ip`     VARCHAR(45)  NOT NULL,
    `created_at`     DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    KEY `idx_username_created` (`username_tried`, `created_at`),
    KEY `idx_ip_created` (`request_ip`, `created_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_persian_ci;

SELECT 'migration_login_throttle با موفقیت اجرا شد.' AS result;
