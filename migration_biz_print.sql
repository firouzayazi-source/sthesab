-- ============================================================
-- محیطِ فروشگاهی — تنظیماتِ چاپ
-- ============================================================
--
-- **خواسته‌ی مالکِ نصب:** «پرینت حساب، تنظیم پرینت هم اضافه بشه.»
--
-- یک ستونِ JSON روی همان `biz_settings` (سربرگِ فاکتور)، نه یک ستون برای هر
-- گزینه: گزینه‌ی تازه‌ی فردا (اندازه‌ی کاغذِ دیگر، لوگو) نباید `ALTER TABLE`
-- بخواهد. معنا و پیش‌فرض‌ها فقط در `Biz::PRINT_DEFAULTS` است و مقدارِ
-- ناشناخته هنگامِ خواندن به پیش‌فرض برمی‌گردد.
--
-- `NULL` یعنی «هنوز چیزی انتخاب نشده» → همه پیش‌فرض. ایدمپوتنت.

ALTER TABLE `biz_settings`
    ADD COLUMN IF NOT EXISTS `print_prefs` VARCHAR(600) NULL DEFAULT NULL
        COMMENT 'تنظیماتِ چاپ (JSON) — Biz::printPrefs()';
