#!/usr/bin/env bash
#
# cron-beat.sh — ثبتِ «این کارِ زمان‌بندی‌شده همین حالا اجرا شد».
#
# با `source` در اسکریپت‌های bash استفاده می‌شود:
#
#     source "$(dirname "$0")/cron-beat.sh"
#     cron_beat backup
#
# ⛔ چرا یک فایلِ ساده و نه دیتابیس: این اسکریپت‌ها (بکاپ، بکاپِ بیرونی،
#    پاک‌سازیِ نشست) اصلاً به دیتابیس وصل نمی‌شوند. وصل کردنشان یعنی
#    گذاشتنِ یک وابستگیِ تازه **دقیقاً روی مسیرِ بکاپ** — جایی که کمترین
#    وابستگی درست‌ترین کار است. یک عددِ اپکِ یونیکس را هم bash می‌نویسد
#    هم PHP می‌خواند.
#
# ⛔ قالب و فهرستِ کارها در `includes/cron_health.php` تعریف شده و همان
#    تنها مرجع است. نامِ کارِ تازه باید **اول آنجا** ثبت شود، وگرنه
#    نشانه نوشته می‌شود ولی پنل مدیر آن را نمی‌شناسد و نشان نمی‌دهد —
#    یعنی همان خرابیِ بی‌صدایی که این ماشین‌آلات برای نبودنش ساخته شد.
#
# ⚠ هیچ‌وقت شکست نمی‌دهد: ثبتِ نشانه کارِ جانبی است و نباید خودِ بکاپ را
#   با یک `set -e` بخواباند.

cron_beat() {
    local job="${1:-}"
    [[ -z "$job" ]] && return 0

    local app_dir beat_dir
    app_dir="${APP_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
    beat_dir="$app_dir/var/cron"

    mkdir -p "$beat_dir" 2>/dev/null || return 0
    date +%s > "$beat_dir/$job.beat" 2>/dev/null || return 0

    # فایل باید برای کاربرِ اپ (`hesab`) خواندنی بماند — پنل مدیر از همان
    # می‌خواند. اینجا root می‌نویسد، پس دسترسیِ پیش‌فرضِ umask کافی نیست.
    chmod 644 "$beat_dir/$job.beat" 2>/dev/null || true
    return 0
}
