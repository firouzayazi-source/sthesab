-- ============================================================
-- محیطِ فروشگاهی — ورودِ اطلاعات از نرم‌افزارِ حسابداریِ دیگر
-- ============================================================
--
-- **خواسته‌ی مالکِ نصب (مهر ۱۴۰۵):** «اشخاص رو هم وارد کنیم … استاندارد کن
-- که اگه کسی خواست از برنامه حسابداری دیگه‌ای وارد بشه بتونه تمام دیتای خودش
-- رو بیاره» — اطلاعاتِ پایه + مانده‌ی اول دوره (همان «سندِ افتتاحیه»).
--
--   ۱. `biz_parties.code` — «کدِ طرف‌حساب» (کدِ شخص در حسابفا، هلو، سپیدار،
--      محک…). هر نرم‌افزاری آن را در خروجیِ اکسل می‌دهد و **کلیدِ تطبیق**
--      است: ورودِ دوباره‌ی همان فایل همان شخص را به‌روز می‌کند، نه تکرار.
--      یکتا در هر فروشگاه (NULL = بی‌کد، چندتا مجاز).
--   ۲. `biz_payments.opening_import` — چکِ در جریانی که از نرم‌افزارِ قبلی
--      آمده (`BizMigrate`). مانده‌ی شخص در فایلِ قبلی این چک را از قبل کم
--      کرده؛ پس مانده‌ی اول دوره به همان اندازه جبران می‌شود و این پرچم
--      می‌گوید چقدرش جبرانِ چک است (`BizParties::chequeComp()`).
--
-- ایدمپوتنت. شاهد: `biz_payments.opening_import`.

ALTER TABLE `biz_parties`
    ADD COLUMN IF NOT EXISTS `code` VARCHAR(30) NULL DEFAULT NULL COMMENT 'کدِ طرف‌حساب — کلیدِ تطبیقِ ورود از فایل';

ALTER TABLE `biz_parties`
    ADD UNIQUE INDEX IF NOT EXISTS `uq_biz_parties_code` (`user_id`, `code`);

ALTER TABLE `biz_payments`
    ADD COLUMN IF NOT EXISTS `opening_import` TINYINT(1) NOT NULL DEFAULT 0
        COMMENT '۱ = چکِ در جریانِ واردشده از نرم‌افزارِ قبلی (BizMigrate)';
