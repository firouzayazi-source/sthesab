-- مهلت «ماندن در حساب»، به دقیقه.
--
-- چرا ستون تازه و نه استفاده از session_hours:
--   کاربر باید بتواند مهلت‌های کوتاه‌تر از یک ساعت هم بگذارد (تا ۱ دقیقه)
--   و همچنین «بدون مهلت» را انتخاب کند. ساعت واحدِ درشتی است و ذخیره‌ی
--   دقیقه داخل ستونی به نام `session_hours` یعنی هر کسی که بعداً آن نام
--   را بخواند، عدد را اشتباه بفهمد.
--
-- معنای مقدارها:
--   0        = بدون مهلت (هرگز دوباره رمز نپرس) — **پیش‌فرض**
--   1..43200 = دقیقه (۴۳۲۰۰ = ۳۰ روز)
--
-- ⚠ ستون قدیمی `session_hours` عمداً حذف نمی‌شود: بکاپ‌های موجود و
--   هر کد قدیمی‌ای که هنوز آن را می‌خواند نباید بشکنند. کدِ فعلی فقط
--   `session_minutes` را می‌خواند.
--
-- ⚠ ردیف‌های موجود عمداً روی همان پیش‌فرض ۰ می‌مانند و از session_hours
--   پر نمی‌شوند. مقدار قبلیِ همه‌ی کاربران «۱ ساعت» بود، ولی آن انتخابِ
--   خودشان نبود — فقط پیش‌فرضِ قدیمی بود. منتقل کردنش یعنی همان
--   آزاردهندگی‌ای که این تغییر برای رفعش نوشته شده. هر کس سخت‌گیری
--   بخواهد، خودش از پروفایل انتخاب می‌کند.

SET @c := (
    SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE()
      AND TABLE_NAME   = 'users'
      AND COLUMN_NAME  = 'session_minutes'
);
SET @s := IF(@c = 0,
    'ALTER TABLE `users` ADD COLUMN `session_minutes` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT ''0 = بدون مهلت'' AFTER `role`',
    'SELECT 1'
);
PREPARE stmt FROM @s;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

